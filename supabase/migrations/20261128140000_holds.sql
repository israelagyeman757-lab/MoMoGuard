-- Withdrawal holds and payer/payee pair history (Track 4 reversal-hold prototype).

CREATE TABLE IF NOT EXISTS public.pair_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer text NOT NULL,
    payee text NOT NULL,
    first_seen timestamptz NOT NULL DEFAULT now(),
    payment_count integer NOT NULL DEFAULT 0,
    UNIQUE (payer, payee)
);

CREATE INDEX IF NOT EXISTS idx_pair_history_payer_payee ON public.pair_history (payer, payee);

ALTER TABLE public.pair_history ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.holds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer text NOT NULL,
    payee text NOT NULL,
    amount double precision NOT NULL,
    risk_level text NOT NULL,
    reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
    hold_minutes integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    release_at timestamptz,
    status text NOT NULL DEFAULT 'held',
    rep_id text,
    sandbox_txn_ref text,
    CONSTRAINT holds_status_chk CHECK (status IN ('held', 'released', 'reversed', 'extended')),
    CONSTRAINT holds_risk_chk CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX IF NOT EXISTS idx_holds_payee_status ON public.holds (payee, status);
CREATE INDEX IF NOT EXISTS idx_holds_status_release ON public.holds (status, release_at);

ALTER TABLE public.holds ENABLE ROW LEVEL SECURITY;