DROP TABLE IF EXISTS public.community_warnings;
DROP TABLE IF EXISTS public.community_reports;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
    id text PRIMARY KEY,
    display_name text NOT NULL,
    role text NOT NULL DEFAULT 'user',
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- reports
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id text NOT NULL,
    phone_number text NOT NULL DEFAULT '',
    scam_type text NOT NULL,
    description text NOT NULL DEFAULT '',
    loss_reported boolean,
    status text NOT NULL DEFAULT 'UNVERIFIED',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_reports_phone ON public.reports (phone_number);
CREATE INDEX IF NOT EXISTS idx_reports_status ON public.reports (status);

ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- numbers (reputation / lookup aggregate)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.numbers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number text NOT NULL UNIQUE,
    current_status text NOT NULL DEFAULT 'unknown',
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.numbers ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- warnings
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.warnings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    scam_type text NOT NULL DEFAULT 'other',
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    CONSTRAINT warnings_status_chk CHECK (status IN ('draft', 'published', 'archived'))
);

CREATE INDEX IF NOT EXISTS idx_warnings_status ON public.warnings (status);

ALTER TABLE public.warnings ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- training
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.training_scenarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    scam_category text NOT NULL,
    explanation text NOT NULL DEFAULT ''
);

ALTER TABLE public.training_scenarios ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.training_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id bigint REFERENCES public.training_scenarios (id) ON DELETE SET NULL,
    question text NOT NULL,
    answer_options jsonb NOT NULL,
    correct_answer text NOT NULL,
    explanation text NOT NULL DEFAULT '',
    scam_category text NOT NULL,
    assessment_tag text NOT NULL DEFAULT 'practice'
);

ALTER TABLE public.training_questions ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.quiz_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    assessment_type text NOT NULL,
    score double precision NOT NULL DEFAULT 0,
    total_questions integer NOT NULL DEFAULT 0,
    completed_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.quiz_attempts ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.quiz_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id bigint NOT NULL REFERENCES public.quiz_attempts (id) ON DELETE CASCADE,
    question_id bigint NOT NULL,
    selected_answer text NOT NULL,
    is_correct boolean NOT NULL
);

ALTER TABLE public.quiz_responses ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.training_recommendations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    category text NOT NULL,
    reason text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.training_recommendations ENABLE ROW LEVEL SECURITY;

